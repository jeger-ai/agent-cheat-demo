#!/usr/bin/env node
// Turn the file lists of a lights-on-software-factory plan into an OpenGantry verify.yaml: the files a step may
// create, modify or delete become allowed_paths; the run's own machinery (.claude/), lockfiles, the plans and the
// contract itself become forbidden_paths. Every other change fails `gantry-verify`, whatever command made it.
//
//   node plan-to-verify.mjs plans/format-greeting.md --step 1.1 --check "node --test src/format-greeting.test.js" > verify.yaml
//   node plan-to-verify.mjs plans/format-greeting.md --allow-new src/format-greeting/   # a step may split into new files there
import { readFileSync } from "node:fs";

const HEADINGS = ["Files to create", "Files to modify", "Files to delete"];
const FORBIDDEN = [".claude", "**/package-lock.json", "**/npm-shrinkwrap.json", "**/yarn.lock", "**/pnpm-lock.yaml", "plans", "verify.yaml"];

function usage(message) {
  console.error(`plan-to-verify: ${message}\nusage: plan-to-verify.mjs <plan.md> [--step <n>] [--allow-new <dir>]... [--check <command>]...`);
  process.exit(2);
}

function parseArgs(argv) {
  const out = { plan: null, step: null, allowNew: [], checks: [] };
  for (let i = 0; i < argv.length; i += 1) {
    const arg = argv[i];
    const value = () => argv[++i] ?? usage(`${arg} needs a value`);
    if (arg === "--step") out.step = value();
    else if (arg === "--allow-new") out.allowNew.push(value().replace(/\/+$/, ""));
    else if (arg === "--check") out.checks.push(value());
    else if (arg.startsWith("-")) usage(`unknown option ${arg}`);
    else if (out.plan === null) out.plan = arg;
    else usage(`one plan only (got ${arg})`);
  }
  if (out.plan === null) usage("name the plan");
  return out;
}

/** The body of `#### Step <n>:`, or the whole document when no step is named (the union of every step). */
function stepBody(text, step) {
  if (step === null) return text;
  const lines = text.split("\n");
  const start = lines.findIndex((l) => l.startsWith(`#### Step ${step}:`));
  if (start === -1) usage(`no "#### Step ${step}:" heading in the plan`);
  const end = lines.findIndex((l, i) => i > start && /^#{1,4} /.test(l));
  return lines.slice(start + 1, end === -1 ? undefined : end).join("\n");
}

/** The paths one heading names: backquoted beside it, or as a numbered list of backquoted paths below it; `none` is empty. */
function filesOf(lines, heading) {
  const out = [];
  lines.forEach((line, i) => {
    if (!line.startsWith(`**${heading}**`)) return;
    const beside = [...line.matchAll(/`([^`]+)`/g)].map((m) => m[1]).filter((p) => p.toLowerCase() !== "none");
    if (beside.length > 0 || /`none`/i.test(line)) return out.push(...beside);
    for (const item of lines.slice(i + 1)) {
      if (item.trim() === "") continue;
      const m = /^\d+\.\s+`([^`]+)`/.exec(item);
      if (!m) break;
      out.push(m[1]);
    }
  });
  return out;
}

const args = parseArgs(process.argv.slice(2));
const lines = stepBody(readFileSync(args.plan, "utf8"), args.step).split("\n");
const files = [...new Set(HEADINGS.flatMap((h) => filesOf(lines, h)))].sort();
if (files.length === 0) usage("the plan names no file in its file lists");

const q = (s) => JSON.stringify(s);
const scope = [...files, ...args.allowNew];
console.log(
  [
    `# Generated by plan-to-verify.mjs from ${args.plan}${args.step ? ` (step ${args.step})` : ""}: the scope a human approved.`,
    "# Commit it before the step runs; gantry-verify reads it from the base commit, so the step cannot widen it.",
    "schema: opengantry.verify.v1",
    "scope:",
    `  allowed_paths: [${scope.map(q).join(", ")}]`,
    `  forbidden_paths: [${FORBIDDEN.map(q).join(", ")}]`,
    ...(args.checks.length > 0 ? ["checks:", ...args.checks.map((c) => `  - { name: ${q(c)}, run: ${q(c)}, expect: exit0 }`)] : []),
  ].join("\n"),
);
